def guard(name, udp, tcp):
    if name == LIVE_NAME or udp in LIVE_PORTS or tcp in LIVE_PORTS:
        sys.exit(f"refusing: {name} / {udp} / {tcp} collides with the dev container ({LIVE_NAME} on 4534/4535)")


def extra_settings(a):
    """--set KEY=VALUE pairs -> extra settings_custom.cfg lines (also the SP_ variant)."""
    lines = []
    for kv in getattr(a, "set", []) or []:
        k, _, v = kv.partition("=")
        lines += [f"{k.strip()} {v.strip()}", f"SP_{k.strip()} {v.strip()}"]
    return chr(10).join(lines)


def docker(*args, check=True, capture=True, timeout=120):
    r = subprocess.run(["docker", *args], capture_output=capture, text=True, timeout=timeout)
    if check and r.returncode != 0:
        raise RuntimeError(f"docker {' '.join(args)} failed: {r.stderr.strip()}")
    return r


class Container:
    def __init__(self, image, name, udp, tcp):
        guard(name, udp, tcp)
        self.image, self.name, self.udp, self.tcp = image, name, udp, tcp
        self.cfg_dir = None

    def start(self, ais, size, rate=30, iq=60, min_players=0, teams_min=1, extra="", ai_mode="teams"):
        self.remove()
        if ai_mode == "teams":
            # one AI-only team per AI (how guest/server/settings_custom.cfg gets its 3 AIs)
            teams_min, num_ais = ais, 0
        else:
            num_ais = ais
        self.cfg_dir = tempfile.mkdtemp(prefix="armacraft-bench-cfg-")
        with open(os.path.join(self.cfg_dir, "settings_custom.cfg"), "w", newline="\n") as f:
            f.write(SETTINGS.format(ais=num_ais, size=size, iq=iq, min_players=min_players, teams_min=teams_min, extra=extra))
        with open(os.path.join(self.cfg_dir, "bridge.cfg"), "w", newline="\n") as f:
            f.write(BRIDGE_CFG.format(rate=rate))
        if ais > 22:
            # the stock aiplayers.cfg has 22 characters and each can be in the game only once (BestIQ
            # skips characters in use), which caps AI players at 22. Clone rows with a numeric suffix.
            self.write_aiplayers(ais)
        docker("run", "-d", "--rm", "--name", self.name,
               "-p", f"127.0.0.1:{self.udp}:4534/udp", "-p", f"127.0.0.1:{self.tcp}:4535/tcp",
               "-v", f"{self.cfg_dir}:/etc/armacraft:ro", self.image)
        log(f"started {self.name} ({self.image}) ais={ais} ({ai_mode}) size_factor={size}")

    def write_aiplayers(self, n):
        stock = docker("run", "--rm", "--entrypoint", "cat", self.image,
                       "/usr/local/etc/games/armagetronad-dedicated/aiplayers.cfg").stdout
        rows = [l for l in stock.splitlines() if l.strip() and not l.startswith("#")]
        out, k = [], 0
        while len(out) < n:
            for r in rows:
                name, rest = r.split(None, 1)
                out.append((name if k == 0 else f"{name}{k + 1}") + "\t" + rest)
            k += 1
        with open(os.path.join(self.cfg_dir, "aiplayers.cfg"), "w", newline="\n") as f:
            f.write("\n".join(out) + "\n")

    def logs(self):
        r = docker("logs", self.name, check=False)
        return (r.stdout or "") + (r.stderr or "")

    def remove(self):
        guard(self.name, self.udp, self.tcp)
        docker("rm", "-f", self.name, check=False)
        if self.cfg_dir:
            shutil.rmtree(self.cfg_dir, ignore_errors=True)
            self.cfg_dir = None


class CpuSampler:
    """Reads the container's cgroup CPU counter through one persistent `docker exec` shell (builtins only)."""

    SCRIPT = (
        "if [ -r /sys/fs/cgroup/cpuacct/cpuacct.usage ]; then F=/sys/fs/cgroup/cpuacct/cpuacct.usage; U=ns; "
        "else F=/sys/fs/cgroup/cpu.stat; U=us; fi; "
        "while read -r _; do read -r l < $F; echo \"$U $l\"; done"
    )

    def __init__(self, name):
        self.p = subprocess.Popen(["docker", "exec", "-i", name, "sh", "-c", self.SCRIPT],
                                  stdin=subprocess.PIPE, stdout=subprocess.PIPE, text=True, bufsize=1)
        self.lock = threading.Lock()

    def sample(self):
        """(perf_counter seconds, cpu seconds) -- the perf_counter is the midpoint of the round trip"""
        with self.lock:
            t0 = time.perf_counter()
            self.p.stdin.write("x\n")
            self.p.stdin.flush()
            line = self.p.stdout.readline().split()
            t1 = time.perf_counter()
        unit, v = line[0], line[-1]
        cpu = int(v) / (1e9 if unit == "ns" else 1e6)
        return (t0 + t1) / 2, cpu, t1 - t0

    def close(self):
        try:
            self.p.stdin.close()
            self.p.terminate()
        except Exception:
            pass


def docker_stats_cpu(name):
    r = docker("stats", "--no-stream", "--format", "{{.CPUPerc}}", name, check=False, timeout=30)
    try:
        return float(r.stdout.strip().rstrip("%"))
    except ValueError:
        return None


