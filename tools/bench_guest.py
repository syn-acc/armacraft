def cmd_deltacheck(a):
    """Two bridge connections to one guest: A stays v1 (full `state`), B sends a host hello asking for
    `delta`. Both get every emitted frame, so folding B's deltas must reproduce A's walls exactly for
    the frame with the same `t`. Reports mismatches and the byte ratio on identical frames."""
    outdir = a.out or tempfile.mkdtemp(prefix="armacraft-bench-delta-")
    os.makedirs(outdir, exist_ok=True)
    c = Container(a.image, a.name, a.udp, a.tcp)
    res = {"kind": "deltacheck", "image": a.image, "ais": a.ais}
    hello_features = None
    try:
        c.start(a.ais, a.size_factor, iq=a.iq, ai_mode=a.ai_mode, extra=extra_settings(a))
        full = Bridge("127.0.0.1", a.tcp)
        _, rno, _ = ramp(full, a.ais)
        dlt = Bridge("127.0.0.1", a.tcp)
        for _, raw in (dlt.pending or []):
            if raw.startswith(b'{"type":"hello"'):
                hello_features = json.loads(raw).get("features")
        dlt.pending = None
        dlt.send({"type": "hello", "proto": 1, "features": ["delta"]})
        full_by_t, delta_by_t = {}, {}
        walls = {}
        seqs = []
        end = time.perf_counter() + a.duration
        while time.perf_counter() < end:
            for ts, raw in full.read_lines(0.02):
                if raw.startswith(b'{"type":"state"'):
                    m = json.loads(raw)
                    # head walls have id 0 in `state` (no net id yet); deltas carry them as -cycle
                    fw = {}
                    for w in m["walls"]:
                        k = w["id"] if w["id"] > 0 else -w["cycle"]
                        if k in fw:
                            res["full_key_collisions"] = res.get("full_key_collisions", 0) + 1
                        fw[k] = dict(w, id=k)
                    full_by_t[m["t"]] = (len(raw) + 1, fw)
            for ts, raw in dlt.read_lines(0.02):
                m = json.loads(raw)
                if m.get("type") == "hello":
                    hello_features = m.get("features")
                elif m.get("type") == "delta":
                    if m.get("key"):
                        walls.clear()
                    for i in m.get("removed", []):
                        walls.pop(i, None)
                    for w in m.get("walls", []):
                        walls[w["id"]] = w
                    seqs.append(m.get("seq"))
                    delta_by_t[m["t"]] = (len(raw) + 1, dict(walls), len(m.get("walls", [])), len(m.get("removed", [])), bool(m.get("key")))
                elif m.get("type") == "state":
                    res.setdefault("v1_states_on_delta_conn", 0)
                    res["v1_states_on_delta_conn"] = res["v1_states_on_delta_conn"] + 1
        full.close()
        dlt.close()
        with open(os.path.join(outdir, "guest_log_deltacheck.txt"), "w", encoding="utf-8") as f:
            f.write(c.logs())
    finally:
        c.remove()
    common = sorted(set(full_by_t) & set(delta_by_t))
    mism = [t for t in common if full_by_t[t][1] != delta_by_t[t][1]]
    fb = [full_by_t[t][0] for t in common]
    db = [delta_by_t[t][0] for t in common if not delta_by_t[t][4]]
    res.update({
        "hello_features": hello_features, "frames_compared": len(common), "mismatched_frames": len(mism),
        "first_mismatch_t": mism[0] if mism else None,
        "full_bytes_mean": mean(fb), "delta_bytes_mean": mean(db), "delta_bytes_p95": pct(db, 95),
        "byte_ratio": mean(db) / mean(fb) if fb and db else None,
        "walls_per_delta_mean": mean([delta_by_t[t][2] for t in common if not delta_by_t[t][4]]),
        "walls_full_mean": mean([len(full_by_t[t][1]) for t in common]),
        "keyframes": sum(1 for t in common if delta_by_t[t][4]),
        "seq_monotonic": all(b == a_ + 1 for a_, b in zip(seqs, seqs[1:])),
    })
    with open(os.path.join(outdir, "deltacheck.json"), "w") as f:
        json.dump(res, f, indent=1)
    log(json.dumps(res, indent=1))
    print(os.path.join(outdir, "deltacheck.json"))


