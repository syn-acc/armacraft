#!/usr/bin/env python3
"""armacraft guest benchmark: what the bridge emits under load, what it costs, how fast input lands.

Runs its OWN container (default name armacraft-guest-bench on 127.0.0.1:4554/udp + 4555/tcp) from an
existing guest image, with a generated config dir mounted over /etc/armacraft. It never touches the
dev container (armacraft-guest, 4534/4535) and refuses to be pointed at it.

Subcommands
  sweep    For each AI count: start a container, connect as a bridge host, record every line for
           --duration seconds (snapshot bytes, walls, cycles, inter-arrival, events), sample guest CPU
           from the container cgroup, then A/B the snapshot stream (BRIDGE_RATE 30 vs ~0 via a `cmd`
           message) to isolate the cost of building/sending snapshots. Saves sampled raw snapshot lines
           and times Python json.loads on them.
  latency  Join one bridge player, send turns at random phase (2 ms polling), time input -> `turn`
           event and input -> first snapshot showing the new direction; also time an idempotent
           re-join -> `joined` round trip (transport + wait for the guest's next main-loop frame).
  deltacheck  For a guest image built with docs/perf-patches/0003-proto-delta-guest.patch: one v1
           connection and one that asks for `delta`; folds the deltas and checks them frame-by-frame
           against the full states (same `t`), and reports the byte ratio.
  parse    Re-time Python json.loads on saved samples_*.jsonl.
  pick     Median- and max-walls frame of each samples file (input for tools/bench/run_java_bench.py).
  synth    Write synthetic state lines (exact guest number format) with N cycles / W walls, for parser
           benchmarks beyond the sizes a real round reaches.
  report   Print markdown tables from a results JSON written by sweep/latency.

  sweep/latency/deltacheck take --image (default armacraft-guest:dev; tag a copy so a rebuild can't
  change it mid-run) and --set SETTING=VALUE for extra guest settings (e.g. DEDICATED_FPS=120).
  sweep --delta asks for `delta` lines, --ab-modes full,delta interleaves v1/delta ON windows
  (both need a guest built with perf patch 0003).

Examples
  docker tag armacraft-guest:dev armacraft-guest:bench
  python tools/bench_guest.py sweep --image armacraft-guest:bench --ais 3,8,16,32 --duration 120 --ab-windows 8
  python tools/bench_guest.py latency --image armacraft-guest:bench --ais 2 --turns 60 [--set DEDICATED_FPS=120]
  python tools/bench_guest.py pick out/samples_*ai.jsonl --out out/pick.jsonl
  python tools/bench_guest.py synth --cycles 32 --walls 100,1000,10000 --out out/synth.jsonl
  python tools/bench/run_java_bench.py out/pick.jsonl out/synth.jsonl
  python tools/bench_guest.py report --results <outdir>/results.json

CPU numbers come from the container's cgroup counter (cpuacct.usage on cgroup v1, cpu.stat usage_usec
on v2), the same counter `docker stats` reads, sampled through one persistent `docker exec` shell that
only uses shell builtins (no fork per sample). `docker stats --no-stream` is also recorded once per A/B
window as a cross-check. 100% = one core; the dedicated server is single-threaded.

Stdlib only. Python 3.9+.
"""

