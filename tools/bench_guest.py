class Bridge:
    def __init__(self, host, port, connect_timeout=30):
        deadline = time.monotonic() + connect_timeout
        last = None
        self.sock = None
        while time.monotonic() < deadline:
            try:
                s = socket.create_connection((host, port), timeout=2)
                s.setsockopt(socket.IPPROTO_TCP, socket.TCP_NODELAY, 1)
                s.setsockopt(socket.SOL_SOCKET, socket.SO_RCVBUF, 4 * 1024 * 1024)
                s.settimeout(0.05)
                # the guest only accepts once its main loop runs; a refused/reset connect is retried
                self.sock = s
                self.buf = b""
                first = self.read_lines(2.0)
                if first:
                    self.pending = first
                    return
                s.close()
            except OSError as e:
                last = e
            time.sleep(0.5)
        raise RuntimeError(f"could not connect to bridge {host}:{port}: {last}")

    def read_lines(self, timeout):
        """Lines that arrive within timeout (returns as soon as at least one full line is there).
        Each item: (perf_counter at recv, bytes line)."""
        out = []
        end = time.perf_counter() + timeout
        while True:
            try:
                chunk = self.sock.recv(1 << 20)
                now = time.perf_counter()
                if not chunk:
                    raise ConnectionError("guest closed the bridge connection")
                self.buf += chunk
                while True:
                    i = self.buf.find(b"\n")
                    if i < 0:
                        break
                    out.append((now, self.buf[:i]))
                    self.buf = self.buf[i + 1:]
            except socket.timeout:
                pass
            if out or time.perf_counter() >= end:
                return out

    def lines(self, poll=0.05):
        """Yield (recv time, line); yield None at least every `poll` s so callers can act on their own
        clock. A small poll (latency bench) keeps sends from being phase-locked to guest frames."""
        if poll < 0.05:
            self.sock.settimeout(poll)
        if getattr(self, "pending", None):
            p, self.pending = self.pending, None
            for x in p:
                yield x
        while True:
            for x in self.read_lines(poll):
                yield x
            yield None  # tick so callers can check their clocks

    def send(self, obj):
        self.sock.sendall((json.dumps(obj, separators=(",", ":")) + "\n").encode())

    def close(self):
        try:
            self.sock.close()
        except Exception:
            pass


