def cmd_latency(a):
    outdir = a.out or tempfile.mkdtemp(prefix="armacraft-bench-lat-")
    os.makedirs(outdir, exist_ok=True)
    c = Container(a.image, a.name, a.udp, a.tcp)
    key = f"mc:bench-{uuid.uuid4().hex[:8]}"
    samples = []
    try:
        c.start(a.ais, a.size_factor, iq=a.iq, ai_mode=a.ai_mode, extra=extra_settings(a))
        bridge = Bridge("127.0.0.1", a.tcp)
        bridge.send({"type": "join", "key": key, "name": "bench", "color": [1, 1, 1]})
        my = {"id": None, "dir": None, "alive": False}
        pending = None  # dict for the turn in flight
        next_turn = 0.0
        pattern = ["left", "right", "right", "left"]
        k = 0
        # echo: an idempotent re-join is answered with `joined` from the guest's next main-loop frame,
        # so its round trip = docker port-forward both ways + the wait for the guest frame (no simulation)
        echo = {"joined": False, "sent": None, "next": 0.0, "rtts": []}
        deadline = time.perf_counter() + a.timeout
        # 2 ms polling: inputs leave at random phase relative to the guest's frames, like real input
        for item in bridge.lines(poll=0.002):
            now = time.perf_counter()
            if now > deadline or len(samples) >= a.turns:
                break
            if item is not None:
                ts, raw = item
                m = json.loads(raw)
                typ = m.get("type")
                if typ == "state":
                    mine = None
                    for cy in m.get("cycles", []):
                        if cy.get("bridge_key") == key:
                            mine = cy
                    if mine is not None:
                        d = (round(mine["dx"], 3), round(mine["dy"], 3))
                        if mine["alive"] and not my["alive"]:
                            log(f"my cycle {mine['id']} alive at t={m.get('t')}")
                            next_turn = ts + 1.0
                        my.update(id=mine["id"], alive=mine["alive"])
                        if pending and "state_r" not in pending and pending["dir_before"] is not None and d != pending["dir_before"]:
                            pending["state_r"] = ts
                            pending["state_t"] = m.get("t")
                        if not mine["alive"] and pending:
                            pending = None
                        my["dir"] = d
                elif typ == "event" and m.get("ev") == "turn" and pending and m.get("id") == my["id"] and "event_r" not in pending:
                    pending["event_r"] = ts
                    pending["event_t"] = m.get("t")
                elif typ == "event" and m.get("ev") == "death" and m.get("id") == my["id"]:
                    log("my cycle died; waiting for the next round")
                    pending = None
                elif typ == "joined":
                    if echo["sent"] is not None:
                        echo["rtts"].append(1000 * (ts - echo["sent"]))
                        echo["sent"] = None
                    elif not echo["joined"]:
                        log(f"joined as {m.get('name')}")
                    echo["joined"] = True
                elif typ == "error":
                    log(f"guest error: {m.get('msg')}")
            if pending and "event_r" in pending and "state_r" in pending:
                samples.append(pending)
                pending = None
            if pending and now - pending["send_r"] > 1.0:
                log("turn timed out (no event/state within 1 s), dropped")
                pending = None
            if echo["joined"] and echo["sent"] is None and len(echo["rtts"]) < a.echo and now >= echo["next"]:
                echo["sent"] = time.perf_counter()
                echo["next"] = now + 0.05 + random.uniform(0, 0.03)
                bridge.send({"type": "join", "key": key, "name": "bench", "color": [1, 1, 1]})
            if my["alive"] and pending is None and now >= next_turn:
                d = pattern[k % len(pattern)]
                k += 1
                pending = {"dir": d, "dir_before": my["dir"], "send_r": time.perf_counter()}
                bridge.send({"type": "input", "key": key, "turn": d})
                next_turn = now + a.interval + random.uniform(0, 0.2)
        bridge.send({"type": "leave", "key": key})
        bridge.close()
        with open(os.path.join(outdir, "guest_log_latency.txt"), "w", encoding="utf-8") as f:
            f.write(c.logs())
    finally:
        c.remove()

    rows = []
    for s in samples:
        rows.append({
            "dir": s["dir"],
            "input_to_event_ms": 1000 * (s["event_r"] - s["send_r"]),
            "input_to_state_ms": 1000 * (s["state_r"] - s["send_r"]),
            "event_to_state_ms": 1000 * (s["state_r"] - s["event_r"]),
        })
    res = {"kind": "latency", "image": a.image, "settings": a.set, "n": len(rows), "rows": rows,
           "echo_ms": {"n": len(echo["rtts"]), "p50": pct(echo["rtts"], 50), "p95": pct(echo["rtts"], 95),
                       "min": min(echo["rtts"]) if echo["rtts"] else None, "max": max(echo["rtts"]) if echo["rtts"] else None}}

    def stat(key):
        xs = [r[key] for r in rows if r[key] is not None]
        return {"p50": pct(xs, 50), "p95": pct(xs, 95), "min": min(xs) if xs else None, "max": max(xs) if xs else None,
                "mean": mean(xs)}

    if rows:
        res["stats"] = {k: stat(k) for k in ("input_to_event_ms", "event_to_state_ms", "input_to_state_ms")}
    with open(os.path.join(outdir, "latency.json"), "w") as f:
        json.dump(res, f, indent=1)
    log(json.dumps(res.get("stats"), indent=1))
    log("echo " + json.dumps(res["echo_ms"]))
    print(os.path.join(outdir, "latency.json"))


