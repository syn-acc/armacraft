def collect(bridge, seconds, sampler, keep_every=1.0, on_state=None, round_no=None, bounds=None):
    """Record every line for `seconds`. Returns a dict of raw series."""
    t_end = time.perf_counter() + seconds
    states, events, others = [], {}, []
    samples, largest = [], None
    last_keep = -1e9
    cpu = [sampler.sample()] if sampler else []
    next_cpu = time.perf_counter() + 1.0
    total_bytes = total_lines = 0
    for item in bridge.lines():
        now = time.perf_counter()
        if sampler and now >= next_cpu:
            cpu.append(sampler.sample())
            next_cpu += 1.0
        if now >= t_end:
            break
        if item is None:
            continue
        ts, raw = item
        total_bytes += len(raw) + 1
        total_lines += 1
        if raw.startswith(b'{"type":"state"') or raw.startswith(b'{"type":"delta"'):
            m = json.loads(raw)
            cyc = m.get("cycles", [])
            walls = m.get("walls", [])
            rec = {"r": ts, "t": m.get("t"), "n": len(cyc), "alive": sum(1 for c in cyc if c.get("alive")),
                   "w": len(walls), "b": len(raw) + 1, "round": round_no,
                   "gaps": sum(1 for w in walls if w.get("gaps"))}
            states.append(rec)
            if on_state:
                on_state(m, ts)
            if ts - last_keep >= keep_every:
                samples.append(raw)
                last_keep = ts
            if largest is None or len(raw) > len(largest):
                largest = raw
            continue
        m = json.loads(raw)
        typ = m.get("type")
        if typ == "event":
            ev = m.get("ev")
            events.setdefault(ev, []).append((ts, m))
        elif typ == "round":
            round_no = m.get("round")
            bounds = m.get("bounds")
            others.append((ts, typ, len(raw) + 1, len(m.get("static", []))))
        else:
            others.append((ts, typ, len(raw) + 1, 0))
    if largest is not None and (not samples or samples[-1] is not largest):
        samples.append(largest)
    if sampler:
        cpu.append(sampler.sample())
    return {"states": states, "events": events, "others": others, "samples": samples, "cpu": cpu,
            "bytes": total_bytes, "lines": total_lines, "seconds": seconds, "bounds": bounds}


def py_parse_times(samples):
    out = []
    for raw in samples:
        s = raw.decode()
        n = max(1, int(200000 / max(1, len(s))))
        best = float("inf")
        for _ in range(5):
            t0 = time.perf_counter()
            for _ in range(n):
                json.loads(s)
            best = min(best, (time.perf_counter() - t0) / n)
        m = json.loads(s)
        out.append({"bytes": len(s) + 1, "walls": len(m.get("walls", [])), "cycles": len(m.get("cycles", [])),
                    "us": best * 1e6})
    return out


def summarize_collect(c):
    st = c["states"]
    secs = c["seconds"]
    res = {"seconds": secs, "lines": c["lines"], "bytes": c["bytes"],
           "msgs_per_s": c["lines"] / secs, "kb_per_s": c["bytes"] / 1024 / secs,
           "states": len(st), "states_per_s": len(st) / secs, "bounds": c["bounds"]}
    if st:
        b = [s["b"] for s in st]
        w = [s["w"] for s in st]
        res.update({
            "snap_bytes_mean": mean(b), "snap_bytes_p50": pct(b, 50), "snap_bytes_p95": pct(b, 95), "snap_bytes_max": max(b),
            "walls_mean": mean(w), "walls_p95": pct(w, 95), "walls_max": max(w),
            "cycles_max": max(s["n"] for s in st), "alive_max": max(s["alive"] for s in st),
            "walls_with_gaps_max": max(s["gaps"] for s in st),
        })
        gaps_ms = [(st[i]["r"] - st[i - 1]["r"]) * 1000 for i in range(1, len(st))
                   if st[i]["round"] == st[i - 1]["round"]]
        gaps_ms = [g for g in gaps_ms if g < 500]
        if gaps_ms:
            hist = {}
            for g in gaps_ms:
                k = int(round(g / 5.0) * 5)
                hist[k] = hist.get(k, 0) + 1
            res.update({"gap_ms_p50": pct(gaps_ms, 50), "gap_ms_p95": pct(gaps_ms, 95), "gap_ms_max": max(gaps_ms),
                        "gap_ms_hist": dict(sorted(hist.items()))})
        # bytes model: bytes = a + b*walls + c*cycles (two-step: subtract per-cycle part using max cycles)
        a, per_wall = linfit(w, b)
        res["bytes_per_wall_fit"] = per_wall
        res["bytes_intercept_fit"] = a
        # walls over round time (per round, bucketed by guest game time)
        by_round = {}
        for s in st:
            by_round.setdefault(s["round"], []).append(s)
        curves = {}
        for r, ss in by_round.items():
            cur = {}
            for s in ss:
                if s["t"] is None:
                    continue
                k = int(math.floor(s["t"] / 10.0) * 10)
                cur.setdefault(k, []).append(s)
            curves[str(r)] = {str(k): {"walls": max(x["w"] for x in v), "bytes": max(x["b"] for x in v),
                                       "alive": min(x["alive"] for x in v)} for k, v in sorted(cur.items())}
            curves[str(r)]["_len_s"] = (ss[-1]["t"] or 0) - (ss[0]["t"] or 0)
        res["rounds"] = curves
    ev = c["events"]
    res["events"] = {k: len(v) for k, v in ev.items()}
    res["turns_per_s"] = len(ev.get("turn", [])) / secs
    cpu = c["cpu"]
    if len(cpu) >= 2:
        res["cpu_pct_mean"] = 100 * (cpu[-1][1] - cpu[0][1]) / (cpu[-1][0] - cpu[0][0])
        per = [100 * (cpu[i][1] - cpu[i - 1][1]) / (cpu[i][0] - cpu[i - 1][0]) for i in range(1, len(cpu))]
        res["cpu_pct_p95_1s"] = pct(per, 95)
        res["cpu_sample_rtt_ms_p50"] = 1000 * pct([x[2] for x in cpu], 50)
    return res


def ab_phase(bridge, sampler, name, windows, window_s, off_rate, modes=("on",)):
    """Alternate OFF (BRIDGE_RATE off_rate) and ON windows (BRIDGE_RATE 30). ON windows cycle through
    `modes`: "on" leaves the stream as it is; "full" / "delta" first send a host hello selecting plain
    `state` or `delta` (guest with perf patch 0003). Every ON window sits between two OFF windows, and
    is compared with their mean (controls for walls growing during the round). Keeps draining the socket."""
    res = []
    last_walls = [None]

    def drain(seconds):
        end = time.perf_counter() + seconds
        for item in bridge.lines():
            if time.perf_counter() >= end:
                return
            if item is None:
                continue
            ts, raw = item
            if raw.startswith(b'{"type":"state"') or raw.startswith(b'{"type":"delta"'):
                m = json.loads(raw)
                last_walls[0] = (len(m.get("walls", [])), sum(1 for c in m.get("cycles", []) if c.get("alive")))

    k = 0
    for i in range(windows):
        on = i % 2 == 1
        mode = "off"
        if on:
            mode = modes[k % len(modes)]
            k += 1
            if mode in ("full", "delta"):
                bridge.send({"type": "hello", "proto": 1, "features": ["delta"] if mode == "delta" else []})
        bridge.send({"type": "cmd", "line": f"BRIDGE_RATE {30 if on else off_rate}"})
        drain(0.75)  # settle
        stats_box = {}
        th = threading.Thread(target=lambda: stats_box.setdefault("v", docker_stats_cpu(name)))
        t0, c0, _ = sampler.sample()
        walls_before = last_walls[0]
        th.start()
        drain(window_s)
        t1, c1, _ = sampler.sample()
        th.join()
        res.append({"on": on, "mode": mode, "cpu_pct": 100 * (c1 - c0) / (t1 - t0), "docker_stats_pct": stats_box.get("v"),
                    "walls_before": walls_before, "walls_after": last_walls[0], "seconds": t1 - t0})
        log(f"  A/B window {i} {mode:5s} cpu={res[-1]['cpu_pct']:.2f}% "
            f"docker_stats={stats_box.get('v')} walls={walls_before}->{last_walls[0]}")
    bridge.send({"type": "cmd", "line": "BRIDGE_RATE 30"})
    ons = [r["cpu_pct"] for r in res if r["on"]]
    offs = [r["cpu_pct"] for r in res if not r["on"]]
    diffs, by_mode = [], {}
    for i, r in enumerate(res):
        if r["on"]:
            nb = [res[j]["cpu_pct"] for j in (i - 1, i + 1) if 0 <= j < len(res) and not res[j]["on"]]
            if nb:
                d = r["cpu_pct"] - mean(nb)
                diffs.append(d)
                by_mode.setdefault(r["mode"], []).append(d)
    return {"windows": res, "cpu_on_mean": mean(ons), "cpu_off_mean": mean(offs),
            "paired_diff_mean": mean(diffs), "paired_diff_min": min(diffs) if diffs else None,
            "paired_diff_max": max(diffs) if diffs else None,
            "paired_diff_by_mode": {m: {"mean": mean(v), "min": min(v), "max": max(v), "n": len(v)} for m, v in by_mode.items()}}


def ramp(bridge, target, timeout=240.0, plateau_rounds=4):
    """The guest adds AIs a few per round (gAIPlayer::SetNumberOfAIs / gAITeam::BalanceWithAIs run once
    per round with a small `tries` budget). End rounds early with an `explode` over the whole arena until
    a round starts with `target` cycles, then return at the start of that round (t ~ 0.5 s)."""
    deadline = time.perf_counter() + timeout
    round_no = checked = None
    bounds = None
    best, stale = 0, 0
    for item in bridge.lines():
        if time.perf_counter() > deadline:
            log(f"  ramp: timeout, best {best} cycles")
            return best, round_no, bounds
        if item is None:
            continue
        ts, raw = item
        if raw.startswith(b'{"type":"round"'):
            m = json.loads(raw)
            round_no, bounds = m.get("round"), m.get("bounds")
            continue
        if not raw.startswith(b'{"type":"state"') or round_no is None or checked == round_no:
            continue
        m = json.loads(raw)
        if (m.get("t") or 0) < 0.5:
            continue
        n = len(m.get("cycles", []))
        checked = round_no
        stale = stale + 1 if n <= best else 0
        best = max(best, n)
        log(f"  ramp: round {round_no} started with {n} cycles (target {target})")
        if n >= target or stale >= plateau_rounds:
            if n < target:
                log(f"  ramp: plateau at {n} cycles, measuring with that")
            return n, round_no, bounds
        b = bounds or [-250, -250, 250, 250]
        cx, cy = (b[0] + b[2]) / 2, (b[1] + b[3]) / 2
        r = min(1000.0, math.hypot(b[2] - b[0], b[3] - b[1]) / 2 + 1)
        bridge.send({"type": "explode", "x": cx, "y": cy, "r": r})
    return best, round_no, bounds


def cmd_sweep(a):
    outdir = a.out or tempfile.mkdtemp(prefix="armacraft-bench-")
    os.makedirs(outdir, exist_ok=True)
    results = {"kind": "sweep", "image": a.image, "size_factor": a.size_factor, "duration": a.duration, "delta": a.delta,
               "started": time.strftime("%Y-%m-%d %H:%M:%S"), "configs": []}
    img = docker("image", "inspect", "--format", "{{.Id}} {{.Created}}", a.image).stdout.strip()
    results["image_id"] = img
    c = Container(a.image, a.name, a.udp, a.tcp)
    try:
        for ais in [int(x) for x in a.ais.split(",")]:
            c.start(ais, a.size_factor, iq=a.iq, ai_mode=a.ai_mode, extra=extra_settings(a))
            sampler = None
            bridge = None
            try:
                bridge = Bridge("127.0.0.1", a.tcp)
                sampler = CpuSampler(a.name)
                log(f"[{ais} AIs] ramping AI count")
                start_cycles, rno, bounds = ramp(bridge, ais)
                if a.delta:
                    # guest built with docs/perf-patches/0003: from here on `walls` = changed walls only
                    bridge.send({"type": "hello", "proto": 1, "features": ["delta"]})
                log(f"[{ais} AIs] collecting {a.duration}s (round {rno}, bounds {bounds})")
                col = collect(bridge, a.duration, sampler, round_no=rno, bounds=bounds)
                summ = summarize_collect(col)
                summ["start_cycles"] = start_cycles
                log(f"[{ais} AIs] {summ.get('states')} states, walls max {summ.get('walls_max')}, "
                    f"snap max {summ.get('snap_bytes_max')} B, {summ['kb_per_s']:.1f} KB/s, cpu {summ.get('cpu_pct_mean', float('nan')):.2f}%")
                ab = None
                if a.ab_windows > 0:
                    log(f"[{ais} AIs] A/B snapshot cost, {a.ab_windows} x {a.ab_window_s}s")
                    ab = ab_phase(bridge, sampler, a.name, a.ab_windows, a.ab_window_s, a.off_rate,
                                  modes=tuple(a.ab_modes.split(",")))
                samp_path = os.path.join(outdir, f"samples_{ais}ai.jsonl")
                with open(samp_path, "wb") as f:
                    for raw in col["samples"]:
                        f.write(raw + b"\n")
                parse = py_parse_times(col["samples"])
                cfg = {"ais": ais, "summary": summ, "ab": ab, "py_parse": parse, "samples_file": samp_path}
                if parse:
                    us_per_kb = [p["us"] / (p["bytes"] / 1024) for p in parse]
                    cfg["py_parse_us_per_kb_p50"] = pct(us_per_kb, 50)
                    big = max(parse, key=lambda p: p["bytes"])
                    cfg["py_parse_largest"] = big
                results["configs"].append(cfg)
                with open(os.path.join(outdir, f"guest_log_{ais}ai.txt"), "w", encoding="utf-8") as f:
                    f.write(c.logs())
            finally:
                if sampler:
                    sampler.close()
                if bridge:
                    bridge.close()
                c.remove()
            with open(os.path.join(outdir, "results.json"), "w") as f:
                json.dump(results, f, indent=1)
    finally:
        c.remove()
    log(f"results: {os.path.join(outdir, 'results.json')}")
    print(os.path.join(outdir, "results.json"))


